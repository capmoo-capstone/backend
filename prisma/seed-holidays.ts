export const allHolidays: HolidayData[] = [...holidays2026, ...holidays2027];

export async function seedHolidays() {
  console.log('Seeding holidays for 2569 (2026) and 2570 (2027)...');
  let count = 0;

  for (const h of allHolidays) {
    const dateObj = new Date(`${h.date}T00:00:00.000Z`);
    await prisma.holiday.upsert({
      where: { date: dateObj },
      update: { name: h.name },
      create: {
        date: dateObj,
        name: h.name,
      },
    });
    count++;
  }

  console.log(`Successfully seeded ${count} holidays!`);
}

if (require.main === module) {
  seedHolidays()
    .catch((e) => {
      console.error('Error seeding holidays:', e);
      process.exit(1);
    })
    .finally(async () => {
      await prisma.$disconnect();
    });
}
